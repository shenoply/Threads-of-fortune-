// Bakes the ground east of the painted map (data/persiaMap.ts eastGround) into data/eastGround.ts, one
// letter a cell, so the game does not work it out cell by cell every time it starts.
//   npx tsx tools/build-east-ground.ts
import { writeFileSync } from 'fs';
import { eastGround, EAST_W } from '../src/data/persiaMap';
import { MASK_W, MASK_H, CELL } from '../src/data/landmask';
const GRID_W = EAST_W / CELL;
const rows: string[] = [];
for (let y = 0; y < MASK_H; y++) {
  let r = '';
  for (let x = MASK_W; x < GRID_W; x++) r += eastGround({ x: x * CELL + CELL / 2, y: y * CELL + CELL / 2 });
  rows.push(r);
}
writeFileSync('src/data/eastGround.ts', `// Generated by tools/build-east-ground.ts from data/persiaMap.ts: the ground east of the painting, a letter a\n// cell (w water, m mountains, h hills, d desert, f fertile). Rebuild after changing persiaMap.ts.\nexport const EAST_ROWS: string[] = ${JSON.stringify(rows)};\n`);
console.log(rows.length, rows[0].length);
